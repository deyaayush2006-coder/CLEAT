"""Writes every PayPal Agent Toolkit tool's name, description and argument schema
to docs/toolkit_tools.txt.

Run from the repo root:  python -m scripts.list_tools
"""

import json
from importlib.metadata import version

from cleat.paypal.tools import raw_tools
from cleat.settings import ROOT

OUTPUT = ROOT / "docs" / "toolkit_tools.txt"


def main() -> None:
    """Write the tool list and print how many tools it contains."""
    tools = raw_tools()
    sections = [
        f"PayPal tools available to Cleat: paypal-agent-toolkit {version('paypal-agent-toolkit')} "
        "plus Cleat's own refund_capture.\n"
        "Generated by scripts/list_tools.py. Regenerate it instead of editing it.\n"
    ]
    for tool in tools:
        schema = json.dumps(tool.args_schema.model_json_schema(), indent=2)
        sections.append(f"== {tool.name} ==\n{tool.description}\n\nArguments:\n{schema}\n")
    OUTPUT.write_text("\n".join(sections), encoding="utf-8", newline="\n")
    print(f"Wrote {len(tools)} tools to {OUTPUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
